#!/usr/bin/env python3
"""
Write prereg/POLICY_REGISTER.md: the ordinary policy register of the five
simulated companies under rulebook revision R2 (Realism revision R2).

One row per provision gives:
  - the policy owner and the citation type (binding instrument or internal standard);
  - the status and any overlay;
  - the tier and the exception authority the canon applies.

The register is generated from the released rulebooks, `rulebook_rev.py` and
`authority.py`, then frozen under the plan hash. EC-01 checks every canon
against it, so a later change to the rule cannot move a tier silently.

    python3 simulation/ec/build_policy_register.py          # write
    python3 simulation/ec/build_policy_register.py --check  # exit 1 if the file on disk differs
"""

from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from simulation.ec import authority as A                        # noqa: E402
from simulation.ec.rulebook_rev import amended_provisions        # noqa: E402

OUT = os.path.join(ROOT, "prereg", "POLICY_REGISTER.md")
PACKS = (("VetPOC", "vetpoc-constitution-corpus"), ("SemiFab", "semifab-constitution-corpus"),
         ("FrontierLLM", "frontierllm-constitution-corpus"), ("DCVigil", "dcvigil-constitution-corpus"),
         ("Meridian Financial", "meridian-corpus"))
AUTH = {None: "", A.OFFICE_SECURITY: "security (CISO)", A.OFFICE_COMPLIANCE: "compliance",
        A.OFFICE_SAFETY: "safety lead", A.OFFICE_LEGAL: "legal counsel", A.OFFICE_ACCESSIBILITY: "accessibility lead"}


def cell(t) -> str:
    return str(t or "").replace("|", "/").replace("\n", " ").strip()


def authority_text(tier: str, office) -> str:
    if tier == "T0":
        return "none: no internal waiver"
    if tier == "T1":
        return AUTH[office] + " (token)"
    if tier == "T2":
        return "the change's reviewer, for an admitted reason with evidence, within bound"
    return "listed contexts only (sampled review)"


def rows():
    for name, d in PACKS:
        with open(os.path.join(ROOT, "simulation", d, "constitution", "rulebook.json")) as fh:
            provs = amended_provisions(json.load(fh)["provisions"])
        for p in provs:
            tier, office, why = A.tier_of(p)
            yield name, p, tier, office, why


def render() -> str:
    L = ["# Policy register of the five simulated companies (rulebook revision R2)", "",
         "*Generated by `simulation/ec/build_policy_register.py` from the released DigitalJudiciary 5.15.0 rulebooks, "
         "the overlay in `simulation/ec/rulebook_rev.py` and the authority rule in `simulation/ec/authority.py`; frozen "
         "under the plan hash and checked against every canon by EC-01. The released rulebooks are unchanged.*", "",
         "Columns:", "",
         "- **owner**: the role that owns the policy (frozen family table).",
         "- **cite**: `binding` means the citation names a statute, regulation, supervisory rule, PCI DSS, or a customer "
         "contract or agreement; `internal` means anything else (a voluntary standard, practice policy, risk "
         "architecture, a benchmark or a commitment).",
         "- **status**: as released, or as overlaid.",
         "- **overlay**: the revision that changed the provision, if any.",
         "- **tier**: the canon tier.",
         "- **exception authority**: who may let a contrary act through.",
         "- **basis**: the branch of the rule that decided the tier.", ""]
    cur = None
    for name, p, tier, office, why in rows():
        if name != cur:
            cur = name
            L += [f"## {name}", "", "| id | family | owner | cite | status | overlay | tier | exception authority | basis |",
                  "|---|---|---|---|---|---|---|---|---|"]
        cite = "binding" if A.binding(p.get("citation") or "") else "internal"
        L.append(f"| {p['id']} | {p['family']} | {A.owner_of(p)} | {cite} | {p.get('status', 'in_force')} | "
                 f"{p.get('amended_by', '')} | {tier} | {authority_text(tier, office)} | {cell(why)} |")
        nxt = None
    L.append("")
    return "\n".join(L)


def load_register(path: str = OUT) -> dict:
    """id -> (tier, exception authority text), parsed from the frozen markdown."""
    out = {}
    with open(path) as fh:
        for line in fh:
            if line.startswith("| ") and not line.startswith("| id ") and not line.startswith("|---"):
                c = [x.strip() for x in line.strip().strip("|").split("|")]
                if len(c) == 9:
                    out[c[0]] = (c[6], c[7])
    return out


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    text = render()
    if "--check" in argv:
        with open(OUT) as fh:
            same = fh.read() == text
        print("ok" if same else "DIFFERS: rerun build_policy_register.py and review the change")
        return 0 if same else 1
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
