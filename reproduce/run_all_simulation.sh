#!/usr/bin/env bash
# Reproduce the five 6,000-case simulation packs (5.8.0; corpus 2.0.0 since 5.9.0, pack 2.4.0 / corpus 2.1.0 since 5.14.0).
# No network, no API key, no pip install. Runtime: about ten minutes on a laptop
# for the full rebuild; about one minute for verification only.
#
#   bash reproduce/run_all_simulation.sh            # verify (default)
#   bash reproduce/run_all_simulation.sh --rebuild  # regenerate, then verify
set -euo pipefail
cd "$(dirname "$0")/.."

PACKS="vetpoc-constitution-corpus semifab-constitution-corpus frontierllm-constitution-corpus dcvigil-constitution-corpus meridian-corpus"
MODE="${1:-verify}"
say(){ printf '\n\033[1m== %s\033[0m\n' "$*"; }

# In the git tree the packs are present as directories. Release archives (one
# per pack, built by reproduce/make_pack_zips.sh and attached to each GitHub
# release) can be dropped into simulation/zips/ instead; they are extracted here
# on first run. Two derived files per pack — corpus/cases.jsonl and
# corpus/explorer_data.json — are not committed and are regenerated by --rebuild.
say "Simulation packs present?"
for p in $PACKS; do
  if [ -d "simulation/$p" ]; then
    printf '%-34s already unpacked\n' "$p"
  else
    z="simulation/zips/$p-$(ls simulation/zips | sed -n "s/^$p-\(.*\)\.zip$/\1/p" | head -1).zip"
    [ -f "$z" ] || { echo "missing archive for $p in simulation/zips/"; exit 1; }
    ( cd simulation && unzip -q "zips/$(basename "$z")" )
    printf '%-34s unpacked from %s\n' "$p" "$(basename "$z")"
  fi
done

say "Simulation packs — 6,000 cases each, 25 categories held identical"
for p in $PACKS; do
  cd "simulation/$p"
  if [ "$MODE" = "--rebuild" ]; then
    python3 generator/build_constitution.py >/dev/null
    python3 generator/build_corpus.py >/dev/null
    python3 generator/build_docs.py >/dev/null
    python3 generator/build_explorer.py >/dev/null
    python3 generator/build_simulation.py >/dev/null
  fi
  CONF=$(python3 harness/run_conformance.py | grep '^RESULT:' | tail -1)
  ANOM=$(python3 -c "import json;print(json.load(open('corpus/manifest.json'))['construction_anomalies'])")
  printf '%-34s %-22s construction anomalies: %s\n' "$p" "$CONF" "$ANOM"
  cd ../..
done

say "Mutation matrices — evidence the suites can fail"
for p in $PACKS; do
  cd "simulation/$p"
  printf '%-34s %s\n' "$p" "$(python3 harness/mutation_matrix.py | grep '^RESULT:' | tail -1)"
  cd ../..
done

say "Numerals — enterprise constitution, inheritance and the federated stream (5.10.0; kernel 5.11.0)"
if [ ! -d simulation/numerals ]; then ( cd simulation && unzip -q zips/numerals-*.zip ); fi
bash simulation/numerals/reproduce/run_all.sh | grep -E "^(RESULT|FC-0|constitution|cases.json|  claude)"

say "Cross-pack route comparison (Chapter 5 RQ3)"
cd simulation/meridian-corpus && python3 harness/compare_packs.py && cd ../..

say "Scenario coverage across the five packs (corpus 2.1.0)"
python3 simulation/tools/coverage_matrix.py | head -12

say "Characterisation as a stage — the extraction round-trip, cued baseline (5.11.0)"
for p in $PACKS; do
  python3 simulation/tools/extraction/run_roundtrip.py "simulation/$p" --backend cued --brief
done

say "Record construction as a stage — cue phrasings, then held-out phrasings (5.12.0)"
for p in $PACKS; do
  python3 simulation/tools/extraction/run_record_stage.py "simulation/$p" --reader cued --brief
  python3 simulation/tools/extraction/run_record_stage.py "simulation/$p" --reader cued --novel-phrasing --brief
done

say "The tolerance sweep on a synthetic magnitude overlay (5.12.0)"
for p in $PACKS; do
  python3 simulation/tools/extraction/dimensional_overlay.py "simulation/$p" --brief
done

say "What an adopted amendment would unsettle — the prior-text rung on an overlay (5.13.0)"
for p in $PACKS; do
  python3 simulation/tools/amendment_overlay.py "simulation/$p" --brief --top 3
done

say "Done."
